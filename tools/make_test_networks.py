def main() -> int:
    print(f"writing to {OUT}")
    write("absurd-but-valid.yaml", absurd_but_valid())
    write("adversarial.yaml", adversarial())
    write("adversarial-rejected.yaml", adversarial_rejected())
    write("bad-references.yaml", bad_references())
    write("id-collision.yaml", id_collision())
    for name, text in INVALID.items():
        write(name, text)
    print("done")
    return 0


if __name__ == "__main__":
    raise SystemExit(main())
