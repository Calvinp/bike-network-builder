#!/usr/bin/env python3
"""Generate the awkward network files used to exercise import and merge.

    python tools/make_test_networks.py

Writes into `tests/fixtures/merge/`. These exist so that "what happens if
someone imports THAT" is a question with an answer you can click on, rather
than a thing you find out from a bug report. Three kinds:

* **valid but strange** — legal v2 that says something nobody would build. A
  corridor of speed humps, a feature with forty treatments, coordinates in the
  Southern Ocean. The FORMAT allows these; the point is that the tool should
  survive them and say something sensible.
* **adversarial** — legal-ish files built to break assumptions: ids that
  collide across namespaces, upgrade chains that loop, geometry with one point,
  names that are only whitespace, numbers where strings belong.
* **invalid** — files that must be REFUSED with a readable message, because
  nothing stops someone hand-editing a file or a download truncating.

Regenerate after changing the format. The files are committed so the JS suite
can read them without running Python.
"""
from __future__ import annotations

import sys
from pathlib import Path

ROOT = Path(__file__).resolve().parent.parent
sys.path.insert(0, str(ROOT))

OUT = ROOT / "tests" / "fixtures" / "merge"

# A small square around Malden, so these overlay the real network usefully.
BOX = [[42.42, -71.08], [42.44, -71.08], [42.44, -71.05], [42.42, -71.05],
       [42.42, -71.08]]


def line(a, b):
    return [[list(a), list(b)]]


HEAD = """# Generated by tools/make_test_networks.py — do not hand-edit.
# {why}
format: bike-network
format_version: 2
crs: EPSG:4326
units: metric
"""


def area_block(id_="a-malden", name="Malden", boundary=True):
    out = ["areas:", f"  - id: {id_}", f"    name: {name}",
           "    kind: municipality", "    context: Massachusetts"]
    if boundary:
        out.append("    boundary:")
        out.append("      - - " + "\n          - ".join(
            f"- {lat}\n            - {lon}" for lat, lon in BOX))
    return "\n".join(out) + "\n"


def write(name: str, text: str) -> None:
    OUT.mkdir(parents=True, exist_ok=True)
    (OUT / name).write_text(text, encoding="utf-8", newline="\n")
    print(f"  {name:34} {len(text):6} bytes")


# ---------------------------------------------------------------------------
# Valid, but nobody would build it
# ---------------------------------------------------------------------------

def absurd_but_valid() -> str:
    """The speed-hump corridor, and friends.

    The registry says speed humps are point-only and the editor will not offer
    one on a line — but the FORMAT allows any treatment on any geometry and
    always will, because a file written by another tool is not wrong for saying
    so. This is what that looks like.
    """
    feats = []
    feats.append(f"""  - id: f-humps
    name: The Endless Speed Hump Corridor
    on_street: Anywhere Street
    notes: >-
      2.4 km of continuous speed humps. Valid YAML, valid v2, and a war crime.
      Here to prove the editor renders a counted treatment on a line as a run
      of glyphs instead of pretending it is a bike lane.
    geometry: {line([42.425, -71.078], [42.437, -71.055])}
    treatments:
      - {{id: t-humps, type: speed_hump, status: proposed, phase: p1,
         quantity: 240}}""")
    feats.append(f"""  - id: f-parking-line
    name: Bike Parking, But As A Road
    geometry: {line([42.428, -71.070], [42.432, -71.062])}
    treatments:
      - {{id: t-parking-line, type: bike_parking, status: existing, quantity: 8}}""")
    stack = "\n".join(
        f"      - {{id: t-stack-{i}, type: {t}, status: proposed, phase: p1}}"
        for i, t in enumerate(
            ["quick_build_separated", "concrete_separated", "shared_use_path",
             "buffered_painted", "neighborway", "pedestrianized",
             "street_trees", "bollards", "parking_removal", "other"], start=1))
    feats.append(f"""  - id: f-everything
    name: Every Treatment At Once
    notes: Ten treatments on one line. The map draws the top-ranked few.
    geometry: {line([42.423, -71.075], [42.441, -71.058])}
    treatments:
{stack}""")
    feats.append("""  - id: f-antarctic
    name: Somewhere Else Entirely
    notes: Valid coordinates, nowhere near the area. Must not be counted.
    geometry: [[[-64.5, -63.5], [-64.6, -63.4]]]
    treatments:
      - {id: t-antarctic, type: shared_use_path, status: existing}""")
    feats.append("""  - id: f-onepoint
    name: A Spot Pretending To Be Nothing
    geometry: [[[42.430, -71.066]]]
    treatments:
      - {id: t-onepoint, type: hawk_signal, status: funded, quantity: 1}""")
    return (HEAD.format(why="Valid v2 that says absurd things. Must IMPORT.")
            + area_block()
            + "authorities:\n  - {id: local, name: City of Malden, level: municipal}\n"
            + "phases:\n  - {id: p1, number: 1, label: Someday}\n"
            + "features:\n" + "\n".join(feats) + "\n")


