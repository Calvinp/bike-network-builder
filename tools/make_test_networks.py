def adversarial_rejected() -> str:
    """The bits of the adversarial file that structure says no to.

    An upgrade loop and a negative count are not matters of taste: one makes
    the phase view unresolvable and the other makes the arithmetic lie.
    """
    return (HEAD.format(why="Hostile AND invalid. Must be REFUSED, readably.")
            + area_block()
            + """authorities:
  - {id: local, name: City of Malden, level: municipal}
phases:
  - {id: p1, number: 1, label: Now}
features:
  - id: f-upgrade-loop\n    name: The Upgrade That Upgrades Itself\n    notes: t-loop-a replaces t-loop-b, which replaces t-loop-a.\n    geometry: [[[42.4290, -71.0700], [42.4330, -71.0630]]]\n    treatments:\n      - {id: t-loop-a, type: buffered_painted, status: existing,\n         upgrades: [t-loop-b]}\n      - {id: t-loop-b, type: concrete_separated, status: proposed, phase: p1,\n         upgrades: [t-loop-a]}\n  - id: f-negative\n    name: Minus Eight Bike Racks\n    geometry: [[[42.4320, -71.0640]]]\n    treatments:\n      - {id: t-negative, type: bike_parking, status: existing, quantity: -8}\n""")


def bad_references() -> str:
    """Upgrades and phases that point at nothing, and a treatment that upgrades
    itself. Structure is strict, so all of these must be REFUSED — but each
    message has to name the thing that is wrong."""
    return (HEAD.format(why="Broken references. Must be REFUSED, readably.")
            + area_block()
            + """authorities:
  - {id: local, name: City of Malden, level: municipal}
phases:
  - {id: p1, number: 1, label: Now}
features:
  - id: f-self-upgrade
    name: Ouroboros Lane
    geometry: [[[42.4300, -71.0680], [42.4310, -71.0660]]]
    treatments:
      - {id: t-self, type: shared_use_path, status: proposed, phase: p1,
         upgrades: [t-self]}
  - id: f-dangling-refs
    name: Points At Nothing
    notes: An authority, a phase and an upgrade target that do not exist.
    geometry: [[[42.4270, -71.0720], [42.4350, -71.0580]]]
    treatments:
      - {id: t-dangling, type: pedestrianized, status: proposed,
         phase: p-nope, authority: ministry-of-silly-walks,
         upgrades: [t-does-not-exist]}
  - id: f-no-name
    geometry: [[[42.4262, -71.0740], [42.4340, -71.0600]]]
    treatments:
      - {id: t-no-name, type: neighborway, status: proposed, phase: p1}
  - id: f-unphased
    name: Proposed With No Phase
    geometry: [[[42.4250, -71.0760], [42.4350, -71.0560]]]
    treatments:
      - {id: t-unphased, type: quick_build_separated, status: proposed}
""")


def id_collision() -> str:
    """One id used for an area, a phase, a feature AND a treatment.

    They share one namespace, so this must be REFUSED — but it has to be
    refused with a message that names the id.
    """
    return (HEAD.format(why="Every namespace reusing one id. Must be REFUSED.")
            + area_block(id_="dup")
            + """authorities:
  - {id: dup, name: Also Dup, level: municipal}
phases:
  - {id: dup, number: 1, label: Dup Again}
features:
  - id: dup
    name: Still Dup
    geometry: [[[42.4300, -71.0700], [42.4340, -71.0620]]]
    treatments:
      - {id: dup, type: quick_build_separated, status: proposed, phase: dup}
""")


